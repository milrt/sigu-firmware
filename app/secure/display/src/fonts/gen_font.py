# Converts the LVGL Montserrat fonts the panel used into font_t tables, so the
# firmware draws the same glyphs without LVGL. Reads external/ and writes the
# .c files next to this script. Run it with no arguments, then check in the
# output.

import math
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
FIRMWARE = os.path.normpath(os.path.join(HERE, "..", "..", "..", "..", ".."))
LVGL_FONTS = os.path.normpath(
    os.path.join(FIRMWARE, "..", "external", "modules", "lib", "gui", "lvgl", "src", "font"))
OUT_DIR = HERE

SIZES = (16, 20, 24)
ASCII_FIRST = 0x20
ASCII_COUNT = 95
CHECK_MARK = 0xF00C


def array_body(src, name):
    m = re.search(r"\b" + re.escape(name) + r"\[\]\s*=\s*\{(.*?)\n\};", src, re.S)
    if not m:
        raise SystemExit("no array " + name)
    return re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S)


def int_array(src, name):
    return [int(t, 0) for t in re.findall(r"-?(?:0x[0-9a-fA-F]+|\d+)", array_body(src, name))]


def field(src, name):
    m = re.search(r"\." + re.escape(name) + r"\s*=\s*(-?\d+)", src)
    if not m:
        raise SystemExit("no field " + name)
    return int(m.group(1))


def glyph_dscs(src):
    pat = (r"\.bitmap_index = (\d+), \.adv_w = (\d+), \.box_w = (\d+), \.box_h = (\d+), "
           r"\.ofs_x = (-?\d+), \.ofs_y = (-?\d+)")
    return [tuple(int(v) for v in g) for g in re.findall(pat, array_body(src, "glyph_dsc"))]


def check_cmaps(src):
    cm = array_body(src, "cmaps")
    starts = [int(v) for v in re.findall(r"\.range_start = (\d+)", cm)]
    ids = [int(v) for v in re.findall(r"\.glyph_id_start = (\d+)", cm)]
    lens = [int(v) for v in re.findall(r"\.range_length = (\d+)", cm)]
    if starts[0] != ASCII_FIRST or lens[0] != ASCII_COUNT or ids[0] != 1:
        raise SystemExit("unexpected ASCII cmap")
    offs = int_array(src, "unicode_list_1")
    return ids[1] + offs.index(CHECK_MARK - starts[1])


def convert(size):
    path = os.path.join(LVGL_FONTS, "lv_font_montserrat_%d.c" % size)
    src = open(path).read()

    if field(src, "bpp") != 4 or field(src, "bitmap_format") != 0:
        raise SystemExit("expected plain 4bpp")
    if field(src, "kern_classes") != 1:
        raise SystemExit("expected kern classes")

    bitmap_in = int_array(src, "glyph_bitmap")
    dscs = glyph_dscs(src)
    gids = list(range(1, 1 + ASCII_COUNT)) + [check_cmaps(src)]
    left_map = int_array(src, "kern_left_class_mapping")
    right_map = int_array(src, "kern_right_class_mapping")
    values = int_array(src, "kern_class_values")
    right_cnt = field(src, "right_class_cnt")
    scale = field(src, "kern_scale")

    line_height = field(src, "line_height")
    base_line = field(src, "base_line")

    bitmap = []
    glyphs = []
    for gid in gids:
        idx, adv, w, h, ox, oy = dscs[gid]
        n = math.ceil(w * h / 2)
        # panel.c decides which bands a text touches from its line box alone.
        top = line_height - base_line - h - oy
        if w and (top < 0 or top + h > line_height):
            raise SystemExit("glyph %d leaves the line box" % gid)
        glyphs.append((len(bitmap), adv, w, h, ox, oy))
        bitmap += bitmap_in[idx:idx + n]

    kern = [(v * scale) >> 4 for v in values]
    if any(k < -128 or k > 127 for k in kern):
        raise SystemExit("kern does not fit int8_t")

    return {
        "size": size,
        "bitmap": bitmap,
        "glyphs": glyphs,
        "left": [left_map[g] for g in gids],
        "right": [right_map[g] for g in gids],
        "kern": kern,
        "right_cnt": right_cnt,
        "line_height": line_height,
        "base_line": base_line,
    }


def rows(values, per_line, fmt):
    out = []
    for i in range(0, len(values), per_line):
        out.append("    " + ", ".join(fmt % v for v in values[i:i + per_line]) + ",")
    return "\n".join(out)


def emit(f):
    lines = [
        "// Generated by gen_font.py from lv_font_montserrat_%d.c. Do not edit."
        % f["size"],
        "// Montserrat and the Font Awesome Free check mark are under the SIL Open Font"
        " License 1.1.",
        "// Copyright notices and license text: OFL.txt.",
        "",
        '#include "drivers/font.h"',
        "",
        "static const uint8_t bitmap[] = {",
        rows(f["bitmap"], 16, "0x%02x"),
        "};",
        "",
        "static const font_glyph_t glyph[FONT_GLYPHS] = {",
    ]
    for g in f["glyphs"]:
        lines.append("    {%d, %d, %d, %d, %d, %d}," % g)
    lines += [
        "};",
        "",
        "static const uint8_t kern_left[FONT_GLYPHS] = {",
        rows(f["left"], 16, "%d"),
        "};",
        "",
        "static const uint8_t kern_right[FONT_GLYPHS] = {",
        rows(f["right"], 16, "%d"),
        "};",
        "",
        "static const int8_t kern[] = {",
        rows(f["kern"], 16, "%d"),
        "};",
        "",
        "const font_t font_%d = {" % f["size"],
        "    .bitmap = bitmap,",
        "    .glyph = glyph,",
        "    .kern_left = kern_left,",
        "    .kern_right = kern_right,",
        "    .kern = kern,",
        "    .kern_right_n = %d," % f["right_cnt"],
        "    .line_height = %d," % f["line_height"],
        "    .base_line = %d," % f["base_line"],
        "};",
        "",
    ]
    return "\n".join(lines)


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    for size in SIZES:
        f = convert(size)
        out = os.path.join(OUT_DIR, "montserrat_%d.c" % size)
        with open(out, "w") as fh:
            fh.write(emit(f))
        print("%s: %d glyphs, %d bitmap bytes, %d kern values" %
              (out, len(f["glyphs"]), len(f["bitmap"]), len(f["kern"])))


if __name__ == "__main__":
    main()
